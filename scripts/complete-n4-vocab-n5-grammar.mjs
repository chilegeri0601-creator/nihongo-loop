function normalizeText(value) {
  return String(value || "").replace(/\s+/g, " ").trim();
}

function decodeHtml(value) {
  return String(value || "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&#8211;/g, "-")
    .replace(/&#8217;/g, "'")
    .replace(/&#038;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

function stripTags(value) {
  return normalizeText(decodeHtml(String(value || "").replace(/<[^>]+>/g, " ")));
}

function getCells(rowHtml) {
  return rowHtml.split(/<td\b[^>]*>/i).slice(1);
}

function inferType(rawType) {
  const type = normalizeText(rawType);
  const found = typeMap.find(([pattern]) => pattern.test(type));
  return found ? found[1] : "词汇";
}

function meaningToChinese(meaning) {
  const clean = normalizeText(meaning)
    .replace(/\b(Noun|Verb|Godan verb|Ichidan verb|Transitive verb|Intransitive verb|Katakana|Adjective|Adverb|Expression|Pronoun|Suffix|Pre-noun adjectival|Suru verb|な-adjective|い-adjective),?\s*/gi, "")
    .replace(/^to check$/i, "check")
    .trim();
  return englishToChinese.get(clean.toLowerCase()) || clean;
}

function slug(value) {
  return String(value)
    .normalize("NFKD")
    .replace(/[^\p{Letter}\p{Number}]+/gu, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

function parseVocabRows(html) {
  const rows = [];
  const rowChunks = html.split(/<tr class=jl-row>/).slice(1);
  for (const chunk of rowChunks) {
    const rowHtml = chunk.split(/<tr class=jl-row>|<\/table>|### JLPT N4 vocab List total/)[0];
    const cells = getCells(rowHtml);
    if (cells.length < 5) continue;

    const number = Number(stripTags(cells[0]));
    if (number < 1 || number > 571) continue;

    const word = stripTags(cells[1]);
    const rawReadingHtml = cells[2];
    const kanaFromP = rawReadingHtml.match(/<p[^>]*>([\s\S]*?)<\/p>/);
    const kana = stripTags(kanaFromP?.[1] || (/[ぁ-んァ-ンー]/.test(word) ? word : rawReadingHtml));
    const rawType = stripTags(cells[3]);
    const meaning = stripTags(cells[4]);

    if (!word || !kana || !meaning) continue;

    rows.push({
      id: `n4-${number}-${slug(kana || word) || number}`,
      word,
      kana,
      meaning: meaningToChinese(meaning),
      type: inferType(rawType),
      example: `「${word}」を使って文を作ります。`,
      exampleMeaning: `用「${word}」造句。`,
    });
  }
  return rows;
}

async function fetchN4Vocabulary() {
  const pages = ["https://jlptsensei.com/jlpt-n4-vocabulary-list/", ...[2, 3, 4, 5, 6].map((page) => `https://jlptsensei.com/jlpt-n4-vocabulary-list/page/${page}/`)];
  const batches = [];
  for (const url of pages) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Failed to fetch ${url}: ${response.status}`);
    batches.push(parseVocabRows(await response.text()));
  }
  const existingByPair = new Map((vocabulary.N4 || []).map((word) => [`${word.word}|${word.kana}`, word]));
  const merged = [];
  const seen = new Set();
  for (const row of batches.flat()) {
    const key = `${row.word}|${row.kana}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const existing = existingByPair.get(key);
    merged.push({ ...(existing || {}), ...row, id: existing?.id || row.id });
  }
  return merged;
}

